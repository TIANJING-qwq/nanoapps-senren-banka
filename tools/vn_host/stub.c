/* Host (PC) stubs for the NanoApps SDK — lets apps/vn/vn.c compile and RUN
 * on a normal computer for rendering verification. NOT part of the device
 * build. /Data/vn/... paths map to build/sb_full/... relative to CWD
 * (run from the NanoApps/ directory). Every audio request is printed so the
 * path construction can be checked. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <stdbool.h>

#include "hb_raw_surface.h"
#include "hb_sdk.h"

static uint32_t s_fb[240 * 432];

uint32_t *hb_raw_fb(void) { return s_fb; }
int hb_raw_w(void) { return 240; }
int hb_raw_h(void) { return 432; }

/* /Data/vn/x -> build/sb_full/x */
static void map_path(char *out, size_t cap, const char *p)
{
    const char *rel = p;
    if (strncmp(rel, "/Data/vn/", 9) == 0) {
        snprintf(out, cap, "build/sb_full/%s", rel + 9);
    } else if (strncmp(rel, "/Data/vn", 8) == 0) {
        snprintf(out, cap, "build/sb_full/%s", rel + 8);
    } else {
        snprintf(out, cap, "%s", rel);
    }
}

uint32_t hb_fs_read(const char *path, void *buf, uint32_t max_size)
{
    char host[512];
    FILE *f;
    size_t n;
    map_path(host, sizeof host, path);
    f = fopen(host, "rb");
    if (!f) return 0;
    n = fread(buf, 1, max_size, f);
    fclose(f);
    return (uint32_t)n;
}

uint32_t hb_fs_read_chunked(const char *path, void *buf, uint32_t max_size)
{
    return hb_fs_read(path, buf, max_size);
}

uint32_t hb_fs_size(const char *path)
{
    char host[512];
    FILE *f;
    long n;
    map_path(host, sizeof host, path);
    f = fopen(host, "rb");
    if (!f) return 0;
    fseek(f, 0, SEEK_END);
    n = ftell(f);
    fclose(f);
    return (uint32_t)n;
}

bool hb_fs_write(const char *path, const void *data, uint32_t size)
{
    char host[512];
    FILE *f;
    map_path(host, sizeof host, path);
    f = fopen(host, "wb");
    if (!f) return false;
    fwrite(data, 1, size, f);
    fclose(f);
    return true;
}

bool hb_audio_play_wav_main(const char *path, uint32_t vol)
{
    char host[512];
    map_path(host, sizeof host, path);
    fprintf(stderr, "[AUDIO] play %s (vol %u) -> %s : %s\n", path, vol,
            host, hb_fs_size(path) ? "EXISTS" : "MISSING");
    return hb_fs_size(path) != 0;
}

